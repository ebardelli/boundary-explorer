let currentLanguage = 'en';

export function setLanguage(lang) {
    if (!lang || lang === currentLanguage) return;
    currentLanguage = lang;
    // notify other modules so they can update visible text
    try {
        window.dispatchEvent(new CustomEvent('languagechange', { detail: { lang: currentLanguage } }));
    } catch (e) {
        // ignore if window not available (e.g. SSR)
    }
}

export function translate(key) {
    const parts = key.split('.');
    let obj = translations[currentLanguage] || {};
    for (const p of parts) {
        obj = obj?.[p];
        if (obj === undefined) return key;
    }
    return obj || key;
}
